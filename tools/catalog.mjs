// Writes docs/catalog.md: every character, card style, card and charm,
// straight from the game files, so the catalog never drifts from the code.
// Run:  node tools/catalog.mjs
import { writeFileSync } from 'node:fs';

globalThis.localStorage = { getItem: () => null, setItem: () => {}, removeItem: () => {} };
const { CARDS, ARCHES } = await import('../src/game/cards.js');
const { CHARMS } = await import('../src/game/charms.js');
const { CHARACTERS, passiveText } = await import('../src/game/characters.js');
const { RULES } = await import('../src/game/battle.js');
const { T } = await import('../src/game/terms.js');
const { OUTFITS } = await import('../src/game/outfits.js');

const RARITY = ['starter', 'common', 'uncommon', 'rare'];
const cell = (s) => String(s).replace(/\|/g, '\\|');
const styles = (d) => [d.arch, d.arch2].filter(Boolean).map((a) => ARCHES[a].name).join(' / ') || '—';
const cardRow = (id) => {
  const d = CARDS[id];
  return `| ${d.name} | ${styles(d)} | ${d.type} | ${d.rarity} | ${cell(d.text(false))} | ${cell(d.text(true))} | ${d.requires ? 'yes' : ''} |`;
};
const cardTable = (ids) => [
  '| Card | Style | Type | Rarity | Effect | Upgraded | Conditional |',
  '|---|---|---|---|---|---|---|',
  ...ids.sort((a, b) => RARITY.indexOf(CARDS[a].rarity) - RARITY.indexOf(CARDS[b].rarity) || CARDS[a].name.localeCompare(CARDS[b].name)).map(cardRow),
].join('\n');

const playable = Object.keys(CARDS).filter((id) => RARITY.includes(CARDS[id].rarity));
const out = [];
out.push('# Kioku Tower catalog', '', '_Generated by `node tools/catalog.mjs` from the game files. Don\'t edit by hand: change the game files and run it again._', '');

out.push('## Characters', '', 'Every card style is open to every character. A character only changes max HP, the starting deck and one passive.', '');
out.push('| Character | Max HP | Passive | Starting deck | Unlock |', '|---|---|---|---|---|');
for (const ch of Object.values(CHARACTERS)) {
  const deck = [...new Set(ch.deck)].map((c) => { const n = ch.deck.filter((x) => x === c).length; return `${n > 1 ? `${n}× ` : ''}${CARDS[c].name}`; }).join(', ');
  out.push(`| ${ch.name} | ${ch.maxHp} | ${cell(passiveText(ch))} | ${deck} | ${ch.unlock ? ch.unlock.text : 'From the start'} |`);
}
out.push('');

out.push('## Couple outfits', '', 'Each set has a matching look for Jenny and Toni, and both unlock together. Open the game with `?unlockall` to unlock everything for testing.', '');
out.push('| Set | Looks | Unlock |', '|---|---|---|');
for (const o of Object.values(OUTFITS)) out.push(`| ${o.name} | ${cell(o.desc)} | ${o.unlock ? o.unlock.text : 'From the start'} |`);
out.push('');

out.push('## Rules for the styles', '');
out.push(`- **${T.sleepy} → ${T.asleep}:** an enemy that reaches ${RULES.sleepAt} ${T.sleepy} falls ${T.asleep} and skips its next ${RULES.sleepTurns} turns (bosses ${RULES.bossSleepTurns}). Its ${T.sleepy} resets, it can't get more while asleep, and each time it wakes up it takes ${RULES.sleepGrow} more ${T.sleepy} to fall asleep again.`);
out.push(`- **${T.cozy}:** on a ${T.cozy} card, healing past your max ${T.hp} hits the enemy for the extra amount.`);
out.push(`- **${T.exposed}:** the enemy takes 50% more damage. Wears off by 1 each enemy turn.`);
out.push('- **No card draw:** anything that would "draw a card" reveals cards instead.');
out.push('- **Hybrid cards** have two styles and count toward both, so mixed decks keep finding cards for either half.');
out.push('- **Conditional cards** stay out of rewards until your deck can use them (for example Roast needs an Exposed card). Starter cards count for conditions but never pick your deck\'s style.', '');

out.push('## Cards by style', '');
for (const [arch, a] of Object.entries(ARCHES)) {
  const ids = playable.filter((id) => CARDS[id].arch === arch || CARDS[id].arch2 === arch);
  out.push(`### ${a.name} (${ids.length})`, '', a.desc, '', cardTable(ids), '');
}
const neutral = playable.filter((id) => !CARDS[id].arch);
out.push(`### No style (${neutral.length})`, '', cardTable(neutral), '');
const hybrids = playable.filter((id) => CARDS[id].arch2);
out.push(`### Hybrids (${hybrids.length})`, '', hybrids.map((id) => `- **${CARDS[id].name}**: ${styles(CARDS[id])}`).join('\n'), '');

out.push('## Charms', '');
const POOLS = { haru: "Haru's Gift (pick 1 of 3 at the start)", drop: 'Drops (treasure, elites, events)', shop: 'Shop only', boss: 'Boss rewards' };
for (const [pool, label] of Object.entries(POOLS)) {
  const ids = Object.keys(CHARMS).filter((k) => CHARMS[k].pool === pool);
  out.push(`### ${label} (${ids.length})`, '', '| Charm | Style | Effect | Conditional |', '|---|---|---|---|');
  for (const k of ids) { const c = CHARMS[k]; out.push(`| ${c.name} | ${c.style ? ARCHES[c.style].name : ''} | ${cell(c.desc)} | ${c.requires ? 'yes' : ''} |`); }
  out.push('');
}

writeFileSync(new URL('../docs/catalog.md', import.meta.url), out.join('\n'));
console.log(`docs/catalog.md: ${playable.length} cards, ${Object.keys(CHARMS).length} charms, ${Object.keys(CHARACTERS).length} characters`);
